import 'dart:convert';
import 'dart:io';
import 'package:json_to_dart_tool/json_parser.dart';

void main(List<String> arguments) {
  if (arguments.isEmpty ||
      arguments.contains('-h') ||
      arguments.contains('--help')) {
    print('''
==================================================
 JSON to Dart CLI Tool
==================================================
Usage:
  dart run bin/json_to_dart.dart -i <input.json> -o <output.dart> --class <ClassName>

Options:
  -i, --input    Path to the input JSON file (Required)
  -o, --output   Path to save the generated Dart file (Optional, prints to console if omitted)
  -c, --class    Name of the root Dart class (Default: AutoGenerated)
  -h, --help     Show this help message
''');
    exit(0);
  }

  String? inputPath;
  String? outputPath;
  String className = 'AutoGenerated';

  for (int i = 0; i < arguments.length; i++) {
    final arg = arguments[i];
    if ((arg == '-i' || arg == '--input') && i + 1 < arguments.length) {
      inputPath = arguments[++i];
    } else if ((arg == '-o' || arg == '--output') && i + 1 < arguments.length) {
      outputPath = arguments[++i];
    } else if ((arg == '-c' || arg == '--class') && i + 1 < arguments.length) {
      className = arguments[++i];
    }
  }

  if (inputPath == null) {
    stderr.writeln('Error: Missing required argument -i / --input');
    exit(1);
  }

  final inputFile = File(inputPath);
  if (!inputFile.existsSync()) {
    stderr.writeln('Error: Input file "$inputPath" does not exist.');
    exit(1);
  }

  try {
    final rawJson = inputFile.readAsStringSync().trim();
    if (rawJson.isEmpty) {
      stderr.writeln('Error: Input JSON file is empty.');
      exit(1);
    }

    final dynamic decoded = jsonDecode(rawJson);
    if (decoded is! Map<String, dynamic>) {
      stderr.writeln('Error: Root JSON must be an object (e.g., { ... }).');
      exit(1);
    }

    final generatedDart = JsonParser.generateDartClass(className, decoded);

    if (outputPath != null) {
      final outputFile = File(outputPath);
      outputFile.writeAsStringSync(generatedDart);
      print('✅ Successfully generated Dart model in: $outputPath');
    } else {
      print('--- Generated Dart Code ---');
      print(generatedDart);
    }
  } on FormatException catch (e) {
    stderr.writeln('Error: Invalid JSON syntax -> ${e.message}');
    exit(1);
  } catch (e) {
    stderr.writeln('Error: Unexpected parsing failure -> $e');
    exit(1);
  }
}
