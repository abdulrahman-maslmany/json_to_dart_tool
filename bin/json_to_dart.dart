import 'dart:convert';
import 'dart:io';
import 'package:json_to_dart_tool/cli_error.dart';
import 'package:json_to_dart_tool/json_parser.dart';

int runCli(List<String> arguments, {StringSink? out, StringSink? err}) {
  final stdoutSink = out ?? stdout;
  final stderrSink = err ?? stderr;

  if (arguments.isEmpty ||
      arguments.contains('-h') ||
      arguments.contains('--help')) {
    stdoutSink.writeln('''
==================================================
 JSON to Dart CLI Tool
==================================================
Usage:
  dart run bin/json_to_dart.dart -i <input.json> -o <output.dart> --class <ClassName>

Options:
  -i, --input    Path to the input JSON file (Required)
  -o, --output   Path to save the generated Dart file (Optional)
  -c, --class    Name of the root Dart class (Default: AutoGenerated)
  -h, --help     Show this help message
''');
    return 0;
  }

  String? inputPath;
  String? outputPath;
  String className = 'AutoGenerated';

  for (int i = 0; i < arguments.length; i++) {
    final arg = arguments[i];
    if ((arg == '-i' || arg == '--input') && i + 1 < arguments.length) {
      inputPath = arguments[++i];
    } else if ((arg == '-o' || arg == '--output') && i + 1 < arguments.length) {
      outputPath = arguments[++i];
    } else if ((arg == '-c' || arg == '--class') && i + 1 < arguments.length) {
      className = arguments[++i];
    }
  }

  if (inputPath == null) {
    final error =
        const CliError('MISSING_ARG', 'Missing required argument -i / --input');
    stderrSink.writeln(error.toString());
    return 1;
  }

  final inputFile = File(inputPath);
  if (!inputFile.existsSync()) {
    final error =
        CliError('FILE_NOT_FOUND', 'Input file "$inputPath" does not exist.');
    stderrSink.writeln(error.toString());
    return 1;
  }

  try {
    final rawJson = inputFile.readAsStringSync().trim();
    if (rawJson.isEmpty) {
      final error = const CliError('EMPTY_INPUT', 'Input JSON file is empty.');
      stderrSink.writeln(error.toString());
      return 1;
    }

    final dynamic decoded = jsonDecode(rawJson);
    if (decoded is! Map<String, dynamic>) {
      final error = const CliError(
          'INVALID_ROOT', 'Root JSON must be an object (e.g., { ... }).');
      stderrSink.writeln(error.toString());
      return 1;
    }

    final generatedDart = JsonParser.generateDartClass(className, decoded);

    if (outputPath != null) {
      final outputFile = File(outputPath);
      outputFile.writeAsStringSync(generatedDart);
      stdoutSink.writeln('Successfully generated Dart model in: $outputPath');
    } else {
      stdoutSink.writeln('--- Generated Dart Code ---');
      stdoutSink.writeln(generatedDart);
    }
    return 0;
  } on FormatException catch (e) {
    final error =
        CliError('INVALID_JSON', 'Invalid JSON syntax -> ${e.message}');
    stderrSink.writeln(error.toString());
    return 1;
  } catch (e) {
    final error =
        CliError('UNEXPECTED_ERROR', 'Unexpected parsing failure -> $e');
    stderrSink.writeln(error.toString());
    return 1;
  }
}

void main(List<String> arguments) {
  exit(runCli(arguments));
}
