import 'dart:convert';
import 'package:flutter/services.dart';
import '../json_parser.dart';

class JsonToolController {
  String generatedCode = '';
  String? errorMessage;

  bool generate(String rawJson, String className) {
    errorMessage = null;
    try {
      final trimmedInput = rawJson.trim();
      if (trimmedInput.isEmpty) {
        errorMessage = 'Please paste a valid JSON string.';
        return false;
      }

      // Decode the raw JSON string into a structured map
      final dynamic decoded = jsonDecode(trimmedInput);
      if (decoded is! Map<String, dynamic>) {
        errorMessage = 'Root JSON must be an object structure (e.g., { ... }).';
        return false;
      }

      final targetClass =
          className.trim().isEmpty ? 'AutoGenerated' : className.trim();

      // Pass class name first, then the decoded map as expected by JsonParser
      generatedCode = JsonParser.generateDartClass(targetClass, decoded);
      return true;
    } on FormatException {
      errorMessage = 'Invalid JSON syntax. Please verify input format.';
      return false;
    } catch (e) {
      errorMessage = 'Error parsing JSON: ${e.toString()}';
      return false;
    }
  }

  Future<void> copyToClipboard() async {
    if (generatedCode.isNotEmpty) {
      await Clipboard.setData(ClipboardData(text: generatedCode));
    }
  }

  void clear() {
    generatedCode = '';
    errorMessage = null;
  }
}
